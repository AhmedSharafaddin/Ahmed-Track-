// منطق استخراج الواجبات من الملفات (الجزء الحتمي، بلا متصفح): جداول بعناوين، نصوص حرة، عناوين التكرار، حدود وملاحظات.
//   node itrack/tests/import.test.mjs
import { extract, fromText, parseCsv, norm } from '../js/import.js';
let pass = 0, fail = 0;
const ok = (n, c, x) => { if (c) { pass++; console.log('PASS', n); } else { fail++; console.log('FAIL', n, x === undefined ? '' : JSON.stringify(x).slice(0, 600)); } };
const by = (r, t) => r.duties.find((d) => d.title.includes(t));

// ١) جدول بعناوين عربية + صف قسم + أرقام هندية
{
  const rows = [['م', 'المهمة', 'التكرار', 'الأولوية', 'المدة', 'ملاحظات'],
    ['١', 'جرد المخزن', 'يومي', 'حرجة', '٣٠ دقيقة', 'مطابقة الجرد بالنظام'],
    ['٢', 'تقرير الحركة', 'أسبوعيًا', 'مهمة', 'ساعة ونصف', ''],
    ['٣', 'إغلاق الشهر', 'شهري', 'عالية', '٢ ساعة', ''],
    ['٤', 'مراجعة العقود', 'سنوي', '', '', ''],
    ['٥', 'مهمة بلا بيانات', '', '', '', '']];
  const r = extract({ tables: [rows], lines: [], strict: false });
  ok('جدول: ٥ واجبات', r.duties.length === 5, r.duties);
  ok('جدول: يومي/حرجة/٣٠ د', by(r, 'جرد') && by(r, 'جرد').freq === 'daily' && by(r, 'جرد').prio === 3 && by(r, 'جرد').est === 30, by(r, 'جرد'));
  ok('جدول: التفاصيل من عمود الملاحظات', by(r, 'جرد').detail === 'مطابقة الجرد بالنظام');
  ok('جدول: أسبوعي ومهمة', by(r, 'تقرير').freq === 'weekly' && by(r, 'تقرير').prio === 2, by(r, 'تقرير'));
  ok('جدول: «ساعة ونصف» لا تُخمَّن (تبقى فارغة بدل قيمة خاطئة)', by(r, 'تقرير').est === 60 || by(r, 'تقرير').est === null, by(r, 'تقرير'));
  ok('جدول: «٢ ساعة» = ١٢٠ دقيقة بقرينة الساعة', by(r, 'إغلاق').est === 120, by(r, 'إغلاق'));
  ok('جدول: «عالية» = مهمة (٢) لا حرجة', by(r, 'إغلاق').prio === 2);
  ok('جدول: السنوي لا يصير دوريًا، ويُسجَّل في التفاصيل مع ملاحظة', by(r, 'عقود').freq === '' && by(r, 'عقود').detail.includes('سنوي') && r.notes.some((x) => x.includes('غير مدعوم')), [by(r, 'عقود'), r.notes]);
  ok('لا اختراع: بلا تكرار ولا مدة ⇒ فارغ وأولوية عادية', by(r, 'بلا بيانات').freq === '' && by(r, 'بلا بيانات').est === null && by(r, 'بلا بيانات').prio === 1, by(r, 'بلا بيانات'));
}
// ٢) عناوين إنجليزية + صفوف أقسام داخل الجدول
{
  const rows = [['Task', 'Frequency', 'Priority', 'Minutes'], ['Daily tasks'], ['Check inbox', 'daily', 'high', '15'], ['Weekly report', 'weekly', 'critical', '60']];
  const r = extract({ tables: [rows], lines: [], strict: false });
  ok('إنجليزي: واجبان بلا صف القسم', r.duties.length === 2, r.duties);
  ok('إنجليزي: قيم صحيحة', by(r, 'inbox').freq === 'daily' && by(r, 'inbox').prio === 2 && by(r, 'inbox').est === 15 && by(r, 'Weekly').prio === 3, r.duties);
}
// ٣) صف قسم «المهام اليومية» يُورّث التكرار لما بعده
{
  const rows = [['المهمة', 'الأولوية'], ['المهام اليومية'], ['فتح المستودع', 'مهمة'], ['المهام الأسبوعية'], ['جرد الرفوف', '']];
  const r = extract({ tables: [rows], lines: [], strict: false });
  ok('قسم في الجدول: التكرار موروث', by(r, 'فتح').freq === 'daily' && by(r, 'جرد').freq === 'weekly' && r.duties.length === 2, r.duties);
}
// ٤) نص حر: غرض + مهام بنقاط + عناوين تكرار + مؤهلات (تُستبعد)
{
  const t = `المسمى الوظيفي: أمين مستودع
الغرض من الوظيفة:
ضمان دقة المخزون وسلامة حركة البضائع.
المهام والمسؤوليات:
المهام اليومية:
• استلام الشحنات ومطابقتها مع أوامر الشراء
• تسجيل حركة الصرف والإدخال في النظام
المهام الأسبوعية:
- جرد عينة من الأصناف
- إعداد تقرير الأصناف الراكدة
المهام الشهرية:
1. إغلاق الجرد الشهري ورفعه للإدارة
المؤهلات والخبرات:
• بكالوريوس في المحاسبة
• خبرة سنتين`;
  const r = extract(fromText(t));
  ok('نص: ٥ واجبات فقط (المؤهلات مستبعدة)', r.duties.length === 5, r.duties.map((d) => d.title));
  ok('نص: التكرار من العنوان', by(r, 'استلام').freq === 'daily' && by(r, 'تقرير').freq === 'weekly' && by(r, 'إغلاق').freq === 'monthly', r.duties);
  ok('نص: المسمى والغرض', r.title === 'أمين مستودع' && r.summary.includes('دقة المخزون'), [r.title, r.summary]);
  ok('نص: لا مؤهلات بين الواجبات', !r.duties.some((d) => d.title.includes('بكالوريوس') || d.title.includes('خبرة')));
}
// ٥) سطر عادي يحوي «المهام اليومية» ليس عنوانًا، وسطر بلا نقاط
{
  const r = extract(fromText('متابعة المهام اليومية للفريق وتوزيعها\nإعداد جدول المناوبات\nالرد على استفسارات الإدارة'));
  ok('أسطر بلا نقاط: كل سطر واجب (٣) ولا يُفهم سطر عادي كعنوان', r.duties.length === 3, r.duties);
}
// ٦) أسطر ملتفّة (PDF): تُضمّ لبندها
{
  const r = extract(fromText('المهام:\n• إعداد التقرير الشهري عن حركة الأصناف\nوتسليمه للمدير المباشر قبل نهاية الشهر\n• متابعة طلبات الشراء'));
  ok('التفاف الأسطر: بندان والثاني ضُمّ لأوله', r.duties.length === 2 && r.duties[0].title.includes('وتسليمه'), r.duties);
}
// ٧) عناوين فرعية تحت المهام لا تُسقط ما بعدها
{
  const r = extract(fromText('المهام والمسؤوليات:\nإدارة المخزون:\n• استلام البضائع\n• ترتيب الرفوف\nالتقارير:\n• إعداد تقرير أسبوعي'));
  ok('عنوان فرعي لا يُنهي القسم', r.duties.length === 3, r.duties.map((d) => d.title));
}
// ٨) حدّ ٤٠ + إزالة التكرار والأرقام المنفردة
{
  const lines = Array.from({ length: 55 }, (_, i) => `• واجب رقم ${i + 1} من القائمة الطويلة`).concat(['• واجب رقم 1 من القائمة الطويلة', '12']);
  const r = extract(fromText(lines.join('\n')));
  ok('حدّ ٤٠ مع ملاحظة', r.duties.length === 40 && r.notes.some((x) => x.includes('40') || x.includes('٤٠')), [r.duties.length, r.notes]);
  const d = extract(fromText('• جرد المخزن\n• جرد المخزن\n• ٣\n• تقرير'));
  ok('تكرار مكرر وأرقام منفردة تُحذف', d.duties.length === 2, d.duties);
}
// ٩) عنوان طويل يُقسَّم لعنوان وتفاصيل
{
  const long = 'إعداد وتحليل تقارير الأداء الشهرية لكل الأقسام ومقارنتها بالخطة السنوية وتحديد الانحرافات الجوهرية، ثم عرضها على الإدارة العليا مع التوصيات المقترحة لمعالجة كل انحراف وفق أولوياته وأثره المالي على الجهة';
  const r = extract(fromText(`• ${long}`));
  ok('عنوان طويل: ≤١٦٠ والباقي في التفاصيل', r.duties[0].title.length <= 160 && r.duties[0].detail.length > 0, [r.duties[0].title.length, r.duties[0].detail.length]);
}
// ٩ب) جدول بلا عناوين (عمودان)
{
  const r = extract({ tables: [[['فحص الطلبات الواردة', 'يوميًا'], ['تحديث قاعدة الموردين', '']]], lines: [], strict: false });
  ok('جدول بلا عناوين: العمود الأول عنوان', r.duties.length === 2 && r.duties[0].title === 'فحص الطلبات الواردة', r.duties);
}
// ٩ج) في PDF (strict) جدول بلا عناوين لا يُفرض: يعود لمنطق النص
{
  const r = extract({ tables: [[['ملخص الوظيفة'], ['فحص الطلبات'], ['تحديث الموردين']]], lines: ['• فحص الطلبات', '• تحديث الموردين'], strict: true, wrap: true });
  ok('PDF بلا عناوين جدول: يُستخدم النص', r.duties.length === 2, r.duties);
}
// ١٠) CSV: فاصلة منقوطة وأقواس وسطر داخل خلية
{
  const rows = parseCsv('﻿المهمة;التكرار;التفاصيل\n"جرد; الرفوف";يومي;"سطر1\nسطر2"\nتقرير;شهري;\n');
  ok('CSV: فاصلة منقوطة وخلية بسطرين', rows.length === 3 && rows[1][0] === 'جرد; الرفوف' && rows[1][2].includes('سطر2'), rows);
  const r = extract({ tables: [rows], lines: [], strict: false });
  ok('CSV: واجبان بتكرارهما', r.duties.length === 2 && r.duties[0].freq === 'daily' && r.duties[1].freq === 'monthly', r.duties);
}
// ١١) التطبيع
ok('norm: همزات وتاء مربوطة وأرقام هندية', norm('المسؤولية ١٢') === 'المسووليه 12', norm('المسؤولية ١٢'));
console.log(`\n${pass} pass, ${fail} fail`); process.exit(fail ? 1 : 0);
